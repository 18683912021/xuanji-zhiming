export const cards: ReadonlyArray<readonly [string, string, string]> = [
  ...majorCards,
  ...suits.flatMap(([name, theme, suggestion]) =>
    ranks.map(
      (rank, index) =>
        [
          name + rank,
          '围绕' + theme + '观察当下的' + movements[index] + '。可以' + suggestion + '。',
          '从' + theme + '的角度查看卡住的地方。先放慢' + movements[index] + '的节奏，再做一项调整。',
        ] as const,
    ),
  ),
]

export type DrawnCard = { index: number; reversed: boolean; position: string }

export function deal() {
  const available = cards.map((_, index) => index)
  for (let i = available.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[available[i], available[j]] = [available[j]!, available[i]!]
  }
  return available.slice(0, 6).map((index) => ({ index, reversed: Math.random() < 0.5 }))
}
